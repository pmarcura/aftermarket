def desenhar(put, sprite, cx, cy, extra=None):
    linhas = [l for l in sprite.strip('\n').split('\n')]
    h = len(linhas); w = max(len(l) for l in linhas)
    for j, l in enumerate(linhas):
        for i, ch in enumerate(l):
            if ch == '.': continue
            put(cx - w // 2 + i, cy - h // 2 + j, LEG[ch])
    if extra:
        for sp, dx, dy in extra:
            desenhar(put, sp, cx + dx, cy + dy)
